"""Flatten the brand mark so it can be drawn as an outline.

    pip install shapely svgpathtools
    python3 scripts/flatten-mark.py <source.svg>

Writes public/brand/mark.svg and regenerates src/assembly/markSvg.ts.

Why this exists: the assembly sequence resolves the mark by taking the boundary of its
geometry, and outlining stroked paths draws every sub-stroke's own contour. The cube's
seam is three bars that all begin at the same centre point, so each contributed a round
cap there and left a rosette at the junction. Expanding the strokes to their true area
and unioning them removes the overlap rather than hiding it.

Subtracting the cube from the cloud moves the artwork's layering into the geometry, so
the cloud's contour stops where the cube covers it without depth-only occluders.

The source keeps its strokes; only the generated copy is flattened.
"""
import sys, xml.etree.ElementTree as ET
from svgpathtools import parse_path
from shapely.geometry import LineString, Polygon
from shapely.ops import unary_union

SRC = sys.argv[1] if len(sys.argv) > 1 else "public/brand/mark.svg"
OUT_SVG, OUT_TS, VIEWBOX = "public/brand/mark.svg", "src/assembly/markSvg.ts", 1000
# 0.3 units in a 1000 viewBox is under a fifth of a pixel at the largest size the mark
# is ever drawn, so simplifying at this tolerance is invisible and cuts the path data
# from ~240 KB to ~5 KB.
STEP, TOL = 1.5, 0.3

paths = {e.attrib.get("id"): dict(e.attrib)
         for e in ET.parse(SRC).getroot().iter() if e.tag.split("}")[-1] == "path"}

def sample(d):
    out = []
    for sub in parse_path(d).continuous_subpaths():
        n = max(8, int(sub.length() / STEP))
        out.append([(p.real, p.imag) for p in (sub.point(i / n) for i in range(n + 1))])
    return out

stroked = [a for a in paths.values() if a.get("stroke", "none") != "none"]
filled = [a for a in paths.values() if a.get("fill", "none") != "none"]

cube = unary_union([
    LineString(pts).buffer(float(a["stroke-width"]) / 2, resolution=24,
                           cap_style="round", join_style="round")
    for a in stroked for pts in sample(a["d"])
])
cloud = unary_union([Polygon(r).buffer(0) for a in filled for r in sample(a["d"])]).difference(cube)
cube, cloud = cube.simplify(TOL, preserve_topology=True), cloud.simplify(TOL, preserve_topology=True)

def to_d(geom):
    polys = list(geom.geoms) if geom.geom_type == "MultiPolygon" else [geom]
    return " ".join("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in ring.coords) + "Z"
                    for p in polys for ring in [p.exterior, *p.interiors])

svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {VIEWBOX} {VIEWBOX}"><g id="Group-copy">'
       f'<path id="Path" fill="#feffff" fill-rule="evenodd" stroke="none" d="{to_d(cloud)}"/>'
       f'<path id="Cube" fill="#feffff" fill-rule="evenodd" stroke="none" d="{to_d(cube)}"/>'
       '</g></svg>')
open(OUT_SVG, "w").write(svg)
open(OUT_TS, "w").write(
    f'''/* The brand mark, inlined verbatim from {OUT_SVG}.
 *
 * That file is a FLATTENED copy of the artwork, generated by scripts/flatten-mark.py:
 * the cube's strokes are expanded to their true area and unioned into one shape, and
 * the cube is subtracted from the cloud. Both steps exist so the mark can be drawn as
 * an outline without self-overlap, and so its layering is part of the geometry rather
 * than faked with depth-only occluders. Run that script again if the artwork changes.
 *
 * Inlined rather than fetched so the sequence has no runtime dependency that can fail.
 */
export const MARK_VIEWBOX = {VIEWBOX};

export const MARK_SVG =
  "{svg.replace(chr(92), chr(92) * 2).replace(chr(34), chr(92) + chr(34))}";
''')
print(f"wrote {OUT_SVG} ({len(svg)/1024:.1f} KB) and {OUT_TS}")
